# GOTY delta self-check (DESIGN §3.5 rule; informational)
# ---------------------------------------------------------------------------

def _expected_lawn_app(name: str, base: int) -> int:
    if name == "frame_duration":
        return base + 0x60
    return base + (0x120 if base >= 0x7F5 else 0x100)


def check_goty_delta(p1051: Profile, pgoty: Profile) -> List[str]:
    """Report fields of ``pgoty`` that do not follow the GOTY delta rule
    relative to ``p1051``: LawnApp +0x100 (>=0x7f5: +0x120, frame_duration
    +0x60), Board offsets >=0x90 +0x18, object fields unchanged.  Known
    exceptions (zombie stride 0x15c->0x168, PlayerInfo layout, zh builds
    +0x124) are expected to appear; the list is informational."""
    out: List[str] = []
    for name, base in p1051.lawn_app.items():
        got = pgoty.lawn_app.get(name)
        if base is None or got is None:
            continue
        exp = _expected_lawn_app(name, base)
        if got != exp:
            out.append("lawn_app.%s: 1051=%#x expected=%#x got=%#x" % (name, base, exp, got))
    for name, base in p1051.board.items():
        got = pgoty.board.get(name)
        if base is None or got is None:
            continue
        exp = base + 0x18 if base >= 0x90 else base
        if got != exp:
            out.append("board.%s: 1051=%#x expected=%#x got=%#x" % (name, base, exp, got))
    for oname, lay in p1051.objects.items():
        other = pgoty.objects.get(oname)
        if other is None:
            continue
        if lay.stride != other.stride:
            out.append("objects.%s.stride: 1051=%s got=%s" % (oname, lay.stride, other.stride))
        for fname, v in lay.fields.items():
            ov = other.fields.get(fname)
            if v is not None and ov is not None and v != ov:
                out.append("objects.%s.%s: 1051=%#x got=%#x" % (oname, fname, v, ov))
    for name, base in p1051.player_info.items():
        got = pgoty.player_info.get(name)
        if base is not None and got is not None and got != base:
            out.append("player_info.%s: 1051=%#x got=%#x" % (name, base, got))
    return out
