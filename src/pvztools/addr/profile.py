# Friendly aliases for the semantic names used in docs/user-scenarios.md and
# the task brief; resolved by Section.__getattr__ / as_address_book lookups.
ALIASES: Dict[str, str] = {
    "clock": "main_counter",
    "game_clock": "main_counter",
    "zombie_array": "zombies",
    "zombie_count": "zombie_count_max",
    "plant_array": "plants",
    "plant_count": "plant_count_max",
    "spawn_type": "allowed_types",
    "lawn": "lawn_app",
    "user_data": "player_info",
    "anim": "effect_system",
    "mower_array": "mowers",
    "grid_item_array": "grid_items",
    # schema_version 2 renames (source-map §7.1); old names keep working
    "items": "coins",
    "item_array": "coins",
    "particle_system_ref": "pool_sparkly_particle_id",
    # community names for the Zombie counters named in source-map §4.3
    "slowed_cd": "chilled_counter",
    "frozen_cd": "ice_trap_counter",
    "hypnotized": "mind_controlled",
    "in_water": "in_pool",
}


class ProfileError(ValueError):
    """Malformed profile data."""


def _parse_hex(value: Any, where: str) -> int:
    if isinstance(value, bool) or value is None:
        raise ProfileError("%s: expected hex string, got %r" % (where, value))
    if isinstance(value, int):
        return value
    if isinstance(value, str):
        try:
            return int(value, 16)
        except ValueError:
            raise ProfileError("%s: not hex-parsable: %r" % (where, value))
    raise ProfileError("%s: expected hex string, got %r" % (where, value))


def _parse_opt_hex(value: Any, where: str) -> Optional[int]:
    return None if value is None else _parse_hex(value, where)


class Section:
    """Read-only name -> int mapping with attribute access (``p.board.sun``)."""

    def __init__(self, name: str, values: Dict[str, Optional[int]]):
        self._name = name
        self._values = dict(values)

    def __getattr__(self, item: str) -> int:
        if item.startswith("_"):
            raise AttributeError(item)
        key = item if item in self._values else ALIASES.get(item, item)
        if key not in self._values:
            raise AttributeError("%s has no field %r" % (self._name, item))
        value = self._values[key]
        if value is None:
            raise AttributeError("%s.%s is not available in this build" % (self._name, key))
        return value

    def __getitem__(self, item: str) -> Optional[int]:
        key = item if item in self._values else ALIASES.get(item, item)
        return self._values[key]

    def __contains__(self, item: str) -> bool:
        return item in self._values or ALIASES.get(item, "") in self._values

    def __iter__(self) -> Iterator[str]:
        return iter(self._values)

    def get(self, item: str, default: Optional[int] = None) -> Optional[int]:
        try:
            return self[item]
        except KeyError:
            return default

    def items(self) -> List[Tuple[str, Optional[int]]]:
        return list(self._values.items())

    def __len__(self) -> int:
        return len(self._values)

    def __repr__(self) -> str:
        body = ", ".join("%s=%s" % (k, hex(v) if v is not None else None) for k, v in self._values.items())
        return "Section(%s: %s)" % (self._name, body)


@dataclass(frozen=True)
class ObjectLayout:
    name: str
    stride: Optional[int]
    fields: Section

    def __getattr__(self, item: str) -> int:
        # delegate field access: p.objects.zombie.dead
        if item.startswith("_") or item in ("name", "stride", "fields"):
            raise AttributeError(item)
        return getattr(self.fields, item)


@dataclass(frozen=True)
class PatchSite:
    rva: int
    on: bytes
    off: bytes
    source: str = ""

    def va(self, image_base: int) -> int:
        return image_base + self.rva


@dataclass(frozen=True)
class PatchGroup:
    name: str
    sites: Tuple[PatchSite, ...]
    level: str = "low"
    excludes: Tuple[str, ...] = ()
    temporary: bool = False
    enabled: bool = True
    disabled_sites: Tuple[str, ...] = ()


@dataclass(frozen=True)
class Function:
    name: str
    rva: Optional[int]
    conv: str
    source: str = ""
    enabled: bool = True
    temp_patch: Optional[Dict[str, Any]] = None

    def va(self, image_base: int) -> Optional[int]:
        return None if self.rva is None else image_base + self.rva


@dataclass
class Profile:
    id: str
    name: str
    lang: str
    stamp: int
    family: str
    conventions: str
    image_base: int
    version_id: int
    verified: bool
    verified_fields: List[str]
    warnings: List[str]
    capability: str
    source: str
    globals_rva: Section
    lawn_app: Section
    board: Section
    objects: Dict[str, ObjectLayout]
    player_info: Section
    patches: Dict[str, PatchGroup]
    functions: Dict[str, Function]
    gates: Dict[str, Any]
    extra: Dict[str, Any]
    achievements_count: int = 0
    field_sources: Dict[str, str] = field(default_factory=dict)
    raw: Dict[str, Any] = field(default_factory=dict, repr=False)
    path: Optional[Path] = None

    # -- convenience -------------------------------------------------------
    @property
    def globals(self) -> Section:
        """Globals as virtual addresses (RVA + image_base)."""
        return Section("globals", {k: (None if v is None else v + self.image_base)
                                   for k, v in self.globals_rva.items()})

    @property
    def is_goty(self) -> bool:
        return self.family.startswith("goty")

    def object(self, name: str) -> ObjectLayout:
        return self.objects[name]

    def function_va(self, name: str) -> Optional[int]:
        return self.functions[name].va(self.image_base)

    def as_address_book(self) -> Dict[str, int]:
        """Flat ``semantic_name -> int``.  Globals / functions / patch sites
        are VAs; struct offsets are relative.  Unavailable entries are omitted."""
        book: Dict[str, int] = {}
        book["image_base"] = self.image_base
        book["stamp"] = self.stamp
        for k, v in self.globals.items():
            if v is not None:
                book["globals." + k] = v
        for sec_name, sec in (("lawn_app", self.lawn_app), ("board", self.board),
                              ("player_info", self.player_info)):
            for k, v in sec.items():
                if v is not None:
                    book["%s.%s" % (sec_name, k)] = v
        for obj_name, lay in self.objects.items():
            if lay.stride is not None:
                book["objects.%s.stride" % obj_name] = lay.stride
            for k, v in lay.fields.items():
                if v is not None:
                    book["objects.%s.%s" % (obj_name, k)] = v
        for fname, fn in self.functions.items():
            va = fn.va(self.image_base)
            if va is not None:
                book["functions." + fname] = va
        for pname, pg in self.patches.items():
            for i, site in enumerate(pg.sites):
                book["patches.%s.%d" % (pname, i)] = site.va(self.image_base)
        return book

    def lookup(self, dotted: str) -> Optional[int]:
        """Resolve ``"board.sun"`` / ``"objects.zombie.hp"`` (aliases allowed)."""
        parts = dotted.split(".")
        if parts[0] == "objects" and len(parts) == 3:
            lay = self.objects.get(parts[1])
            if lay is None:
                return None
            return lay.stride if parts[2] == "stride" else lay.fields.get(parts[2])
        if len(parts) == 2:
            sec = {"globals": self.globals, "lawn_app": self.lawn_app, "board": self.board,
                   "player_info": self.player_info}.get(parts[0])
            if sec is not None:
                return sec.get(parts[1])
            if parts[0] == "functions" and parts[1] in self.functions:
                return self.function_va(parts[1])
        return None


