_REQUIRED = ("id", "name", "lang", "stamp", "family", "image_base", "globals",
             "lawn_app", "board", "objects", "patches", "functions")
_FAMILIES = ("retail", "goty", "goty_zh2010_ja", "goty_zh2012", "beta")


def _section(name: str, raw: Dict[str, Any]) -> Section:
    if not isinstance(raw, dict):
        raise ProfileError("%s: expected object" % name)
    return Section(name, {k: _parse_opt_hex(v, "%s.%s" % (name, k)) for k, v in raw.items()})


def _bytes(s: Any, where: str) -> bytes:
    if not isinstance(s, str) or len(s) % 2 or not s:
        raise ProfileError("%s: bad byte string %r" % (where, s))
    try:
        return bytes.fromhex(s)
    except ValueError:
        raise ProfileError("%s: bad byte string %r" % (where, s))


def profile_from_dict(d: Dict[str, Any], path: Optional[Path] = None) -> Profile:
    for key in _REQUIRED:
        if key not in d:
            raise ProfileError("profile missing %r" % key)
    family = d["family"]
    if family not in _FAMILIES:
        raise ProfileError("unknown family %r" % family)
    image_base = _parse_hex(d["image_base"], "image_base")

    globals_rva = Section("globals", {
        k: _parse_opt_hex(v["rva"] if isinstance(v, dict) else v, "globals." + k)
        for k, v in d["globals"].items()})
    lawn_app = _section("lawn_app", d["lawn_app"])
    board = _section("board", d["board"])
    player_info = _section("player_info", d.get("player_info", {}))

    objects: Dict[str, ObjectLayout] = {}
    for oname, lay in d["objects"].items():
        objects[oname] = ObjectLayout(
            oname, _parse_opt_hex(lay.get("stride"), "objects.%s.stride" % oname),
            _section("objects." + oname, lay.get("fields", {})))

    patches: Dict[str, PatchGroup] = {}
    for pname, pg in d["patches"].items():
        sites = []
        for i, s in enumerate(pg.get("sites", [])):
            where = "patches.%s[%d]" % (pname, i)
            on, off = _bytes(s["on"], where), _bytes(s["off"], where)
            if len(on) != len(off):
                raise ProfileError("%s: on/off width mismatch" % where)
            sites.append(PatchSite(_parse_hex(s["rva"], where), on, off, s.get("source", "")))
        patches[pname] = PatchGroup(
            pname, tuple(sites), pg.get("level", "low"), tuple(pg.get("excludes", ())),
            bool(pg.get("temporary", False)), bool(pg.get("enabled", True)),
            tuple(pg.get("disabled_sites", ())))

    functions: Dict[str, Function] = {}
    for fname, fn in d["functions"].items():
        rva = _parse_opt_hex(fn.get("rva"), "functions." + fname)
        tp = fn.get("temp_patch")
        if tp is not None:
            tp = dict(tp)
            for k in ("row_site", "col_site"):
                tp[k] = _parse_opt_hex(tp.get(k), "functions.%s.temp_patch.%s" % (fname, k))
        functions[fname] = Function(fname, rva, fn.get("conv", ""), fn.get("source", ""),
                                    bool(fn.get("enabled", rva is not None)), tp)

    p = Profile(
        id=d["id"], name=d["name"], lang=d["lang"], stamp=_parse_hex(d["stamp"], "stamp"),
        family=family, conventions=d.get("conventions", family), image_base=image_base,
        version_id=int(d.get("version_id", 0)), verified=bool(d.get("verified", False)),
        verified_fields=list(d.get("verified_fields", [])), warnings=list(d.get("warnings", [])),
        capability=d.get("capability", "FULL"), source=d.get("source", ""),
        globals_rva=globals_rva, lawn_app=lawn_app, board=board, objects=objects,
        player_info=player_info, patches=patches, functions=functions,
        gates=dict(d.get("gates", {})), extra=dict(d.get("extra", {})),
        achievements_count=int(d.get("achievements_count", 0)),
        field_sources=dict(d.get("field_sources", {})), raw=d, path=path,
    )
    validate(p)
    return p


def validate(p: Profile) -> None:
    """Sanity checks beyond hex-parsability; raises ProfileError."""
    if p.globals_rva.get("lawn_app") is None:
        raise ProfileError("%s: globals.lawn_app missing" % p.id)
    if p.image_base != 0x400000:
        raise ProfileError("%s: unexpected image_base %s" % (p.id, hex(p.image_base)))
    for name in ("board", "game_mode", "game_ui"):
        if p.lawn_app.get(name) is None:
            raise ProfileError("%s: lawn_app.%s missing" % (p.id, name))
    if not (0x700 <= p.lawn_app.board <= 0x900):
        raise ProfileError("%s: lawn_app.board out of range" % p.id)
    for name in ("sun", "main_counter", "zombies", "plants", "spawn_list", "seed_bank"):
        if p.board.get(name) is None:
            raise ProfileError("%s: board.%s missing" % (p.id, name))
    if not (0x5000 <= p.board.sun <= 0x6000):
        raise ProfileError("%s: board.sun out of range" % p.id)
    for oname in ("zombie", "plant"):
        lay = p.objects.get(oname)
        if lay is None or not lay.stride:
            raise ProfileError("%s: objects.%s.stride missing" % (p.id, oname))
    for fn in p.functions.values():
        if fn.rva is not None and fn.rva >= 0x400000:
            raise ProfileError("%s: functions.%s looks like a VA, expected RVA" % (p.id, fn.name))
    for pg in p.patches.values():
        for s in pg.sites:
            if s.rva >= 0x400000:
                raise ProfileError("%s: patches.%s site looks like a VA" % (p.id, pg.name))


def load_profile(path: Union[str, Path]) -> Profile:
    path = Path(path)
    with open(path, "r", encoding="utf-8") as fh:
        d = json.load(fh)
    return profile_from_dict(d, path)


def load_index(profile_dir: Optional[Path] = None) -> Dict[str, Any]:
    base = Path(profile_dir) if profile_dir else PROFILE_DIR
    with open(base / "index.json", "r", encoding="utf-8") as fh:
        return json.load(fh)


def profile_for_stamp(stamp: Union[int, str], profile_dir: Optional[Path] = None) -> Optional[Profile]:
    """Look up a profile by PE TimeDateStamp (int or hex string)."""
    base = Path(profile_dir) if profile_dir else PROFILE_DIR
    key = "0x%x" % (int(stamp, 16) if isinstance(stamp, str) else int(stamp))
    fn = load_index(base).get("by_stamp", {}).get(key)
    if fn is None:
        return None
    return load_profile(base / fn)


def profile_for_id(profile_id: str, profile_dir: Optional[Path] = None) -> Optional[Profile]:
    base = Path(profile_dir) if profile_dir else PROFILE_DIR
    for entry in load_index(base).get("profiles", []):
        if entry["id"] == profile_id:
            return load_profile(base / entry["file"])
    return None


def list_profiles(profile_dir: Optional[Path] = None) -> List[Dict[str, Any]]:
    """Index entries (id, file, stamp, name, family, verified), no loading."""
    return list(load_index(profile_dir).get("profiles", []))


