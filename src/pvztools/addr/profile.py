"""Address profiles (L1 version table) for official PvZ1 builds.

A profile is a JSON document generated by ``tools/import_toolkit_profiles.py``
(see docs/parity-pvztoolkit.md §6).  Only semantic names appear here
(``p.board.sun``); Toolkit identifiers survive only under ``extra``.

Conventions
-----------
* Static addresses (``globals``, ``functions``, patch sites) are stored as
  RVA.  Attribute access returns the **virtual address** (RVA + image_base)
  because every official build loads at 0x400000 without ASLR; ``rva(...)``
  helpers give the raw value.
* Struct offsets (``lawn_app``, ``board``, ``objects.<obj>.fields``) are
  plain ints relative to their struct base.
* ``as_address_book()`` flattens everything to ``"section.name" -> int``.
"""
from __future__ import annotations

